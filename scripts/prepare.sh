#!/usr/bin/env bash
# Turn a checkout of zulip/zulip-flutter into the iphoneblog app.
#
#   scripts/prepare.sh <upstream-checkout>
#
# Runs on macOS (sips, PlistBuddy). Every step checks that it found what it
# changes, so a new upstream release that moved something fails here, loudly,
# instead of building an app that still says Zulip or still uses Firebase.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
up="$(cd "${1:?usage: prepare.sh <upstream-checkout>}" && pwd)"
# shellcheck source=../config/app.env
source "$here/config/app.env"

say() { printf '== %s\n' "$*"; }
die() { printf 'prepare.sh: %s\n' "$*" >&2; exit 1; }

# Replace exactly one occurrence of $2 by $3 in file $1, or fail.
replace_once() {
  python3 - "$@" <<'EOF'
import sys
path, old, new = sys.argv[1:4]
s = open(path, encoding='utf-8').read()
n = s.count(old)
if n != 1:
    sys.exit(f"prepare.sh: expected 1 match in {path}, found {n}: {old!r}")
open(path, 'w', encoding='utf-8').write(s.replace(old, new))
EOF
}

# Replace every occurrence; fail if there is none.
replace_all() {
  python3 - "$@" <<'EOF'
import sys
path, old, new = sys.argv[1:4]
s = open(path, encoding='utf-8').read()
if old not in s:
    sys.exit(f"prepare.sh: no match in {path}: {old!r}")
open(path, 'w', encoding='utf-8').write(s.replace(old, new))
EOF
}

say "overlay: our own files"
cp -R "$here/overlay/." "$up/"

say "config: lib/iphoneblog/config.g.dart"
mkdir -p "$up/lib/iphoneblog"
cat > "$up/lib/iphoneblog/config.g.dart" <<EOF
// Generated by scripts/prepare.sh from config/app.env. Do not edit.
import 'dart:ui';

const kIphoneblogServerUrl = '$SERVER_URL';
const kIphoneblogAuthCallbackScheme = '$AUTH_CALLBACK_SCHEME';
const kIphoneblogBrandColor = Color(0xff$BRAND_COLOR);
EOF

say "patches"
for p in "$here"/patches/*.patch; do
  echo "   $(basename "$p")"
  git -C "$up" apply --whitespace=nowarn "$p" || die "patch $(basename "$p") does not apply to this release"
done

say "pubspec: Firebase stand-ins and the native plugin"
replace_once "$up/pubspec.yaml" $'\ndependencies:\n' \
$'\ndependencies:\n  iphoneblog_native:  # iphoneblog\n    path: ./packages/iphoneblog_native\n'
replace_once "$up/pubspec.yaml" $'\ndependency_overrides:\n' \
$'\ndependency_overrides:\n  # iphoneblog: no Firebase; see packages/firebase_messaging.\n  firebase_core:\n    path: ./packages/firebase_core\n  firebase_messaging:\n    path: ./packages/firebase_messaging\n'

say "push: encrypt the token to our relay's key, not Zulip's"
python3 - "$up/lib/model/push_device.dart" "$RELAY_PUBLIC_KEY" <<'EOF2'
import base64, re, sys
path, key = sys.argv[1:3]
if len(base64.b64decode(key, validate=True)) != 32:
    sys.exit("prepare.sh: RELAY_PUBLIC_KEY is not 32 bytes of base64")
s = open(path).read()
s, n = re.subn(r"(static final bouncerPublicKey = base64Decode\()'[A-Za-z0-9+/=]+'(\);).*",
               lambda m: f"{m.group(1)}'{key}'{m.group(2)} // iphoneblog: our relay", s)
if n != 1:
    sys.exit(f"prepare.sh: expected 1 bouncerPublicKey line in {path}, found {n}")
open(path, 'w').write(s)
EOF2

say "ids: bundle id, team, app group"
replace_all "$up/ios/Runner.xcodeproj/project.pbxproj" 'org.zulip.Zulip' "$BUNDLE_ID"
python3 - "$up/ios/Flutter/Zulip.xcconfig" "$TEAM_ID" "$APP_GROUP" <<'EOF'
import re, sys
path, team, group = sys.argv[1:4]
s = open(path).read()
s, n1 = re.subn(r'(?m)^DEVELOPMENT_TEAM=.*$', f'DEVELOPMENT_TEAM={team}', s)
s, n2 = re.subn(r'(?m)^ZULIP_APP_GROUP_IDENTIFIER=.*$', f'ZULIP_APP_GROUP_IDENTIFIER={group}', s)
if (n1, n2) != (1, 1):
    sys.exit(f"prepare.sh: Zulip.xcconfig changed shape ({n1}, {n2})")
open(path, 'w').write(s)
EOF
replace_once "$up/lib/model/store.dart" "'group.com.zulip.app'" "'$APP_GROUP'"

say "Info.plist: name, no URL scheme, permission texts"
pb=/usr/libexec/PlistBuddy
plist="$up/ios/Runner/Info.plist"
$pb -c "Set :CFBundleDisplayName $APP_NAME" "$plist"
$pb -c "Set :CFBundleName $APP_NAME" "$plist"
$pb -c "Delete :CFBundleURLTypes" "$plist"
$pb -c "Set :NSCameraUsageDescription Take photos and send them in $APP_NAME." "$plist"
$pb -c "Set :NSPhotoLibraryUsageDescription Choose photos from your library and send them in $APP_NAME." "$plist"

say "icon and launch colour"
set_dir="$up/ios/Runner/Assets.xcassets/AppIcon.appiconset"
for f in "$set_dir"/*.png; do
  w=$(sips -g pixelWidth "$f" | awk '/pixelWidth/ {print $2}')
  sips -s format png -z "$w" "$w" "$here/brand/icon-1024.png" --out "$f" >/dev/null
done
python3 - "$up/ios/Runner/Assets.xcassets/LaunchBackground.colorset/Contents.json" "$BRAND_COLOR" <<'EOF'
import json, sys
path, hexc = sys.argv[1:3]
d = json.load(open(path))
r, g, b = (f"0x{hexc[i:i+2].upper()}" for i in (0, 2, 4))
for c in d['colors']:
    c['color']['components'].update(red=r, green=g, blue=b)
json.dump(d, open(path, 'w'), indent=2)
EOF

say "check: nothing of Firebase or the zulip scheme left on iOS"
! grep -q '<string>zulip</string>' "$plist" || die "Info.plist still registers zulip://"
! grep -rq 'org.zulip.Zulip' "$up/ios/Runner.xcodeproj/project.pbxproj" || die "bundle id not replaced"

say "done: $(cd "$up" && git describe --tags --always) prepared for $BUNDLE_ID"
